"""The site's download claims are checked against the bytes, here, on every run.

`docs/downloads/manifest.json` is generated by ``scripts/audit_downloads.py --write`` from the
rasters on disk, joined with the hand-authored claims in ``docs/downloads/verdicts.json``.  The
rule these tests enforce is the one the standing brief asks for and the one a hand-written table
cannot keep: *a page may not state anything about a downloadable file that its bytes disagree
with.*  If a raster is regenerated without re-running the audit, if a hash on the site goes
stale, or if a file at the site root appears without a verdict, a test here fails.

No fixtures are invented: everything is read from the repository as committed.
"""
from __future__ import annotations

import hashlib
import importlib.util
import json
import pathlib
import re
import sys

import pytest

ROOT = pathlib.Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT / "src"))

from gems62 import grid as G  # noqa: E402

DL = ROOT / "docs/downloads"
PAGES = ("docs/index.html", "docs/executive-summary.html", "docs/executive-summary-v2.html",
         "docs/results.html", "docs/run-card.html")


def _manifest() -> dict:
    path = DL / "manifest.json"
    assert path.exists(), ("docs/downloads/manifest.json is missing; run "
                           "`python scripts/audit_downloads.py --write`")
    return json.loads(path.read_text())


def _audit():
    spec = importlib.util.spec_from_file_location("audit_downloads", ROOT / "scripts/audit_downloads.py")
    mod = importlib.util.module_from_spec(spec)
    assert spec.loader is not None
    spec.loader.exec_module(mod)
    return mod


def _sha(path: pathlib.Path) -> str:
    h = hashlib.sha256()
    h.update(path.read_bytes())
    return h.hexdigest()


def test_manifest_problems_empty():
    man = _manifest()
    assert man.get("problems") == [], f"the download audit still reports problems: {man['problems']}"


def test_recorded_hashes_sizes_and_dots_match_the_bytes_on_disk():
    man = _manifest()
    for row in man["files"]:
        p = ROOT / row["path"]
        assert p.exists(), f"{row['path']} is in the manifest but not on disk"
        assert p.stat().st_size == row["bytes"], f"{p.name}: size changed since the audit"
        assert _sha(p) == row["sha256"], (
            f"{p.name}: sha256 is {_sha(p)[:16]} on disk, {row['sha256'][:16]} in the manifest - "
            "the site would be describing different bytes; re-run the audit with --write")


def test_every_site_root_raster_carries_a_verdict_sidecar():
    man = _manifest()
    shipped = [r for r in man["files"] if r["path"].startswith("docs/downloads/")
               and r["path"].endswith(".tif")]
    assert len(shipped) >= 7, "the site's download directory lost files and nobody noticed"
    names = {pathlib.Path(r["path"]).name for r in shipped}
    on_disk = {p.name for p in DL.glob("*.tif")}
    assert names == on_disk, f"manifest and directory disagree: {names ^ on_disk}"
    for row in shipped:
        side = DL / (re.sub(r"\.tif$", "", row["path"].split("/")[-1]) + ".verdict.json")
        assert side.exists(), f"{row['path']} is shipped with no verdict sidecar at {side.name}"
        v = json.loads(side.read_text())
        assert v["sha256"] == row["sha256"], f"{side.name}: pins a different sha than the file"
        assert v["bytes"] == row["bytes"], f"{side.name}: pins a different size than the file"
        assert v["verdict"], f"{side.name}: empty verdict"
        assert v.get("artifact_of"), f"{side.name}: must say which script produced the artifact"


def test_no_download_claims_it_is_ok_to_submit_without_a_confirmed_score():
    for row in _manifest()["files"]:
        if not row["path"].startswith("docs/downloads/"):
            continue
        side = DL / (re.sub(r"\.tif$", "", row["path"].split("/")[-1]) + ".verdict.json")
        v = json.loads(side.read_text())
        if v.get("ok_to_submit"):
            assert v.get("organizer_score") is not None, (
                f"{row['path']}: labelled OK to submit but no organiser-confirmed score exists; "
                "this repository's rule is that a claim of legality is not a claim of merit")
        assert v.get("format_legal") == row.get("format_legal"), (
            f"{row['path']}: the sidecar and the audit disagree about format legality")


def test_illegal_files_are_labelled_or_flagged_for_their_owning_lane():
    """At the site root a broken file must be labelled; in a lane directory it must be *named*."""
    man = _manifest()
    for row in man["files"]:
        if row.get("format_legal") is not False:
            continue
        if row["path"].startswith("docs/downloads/"):
            txt = (row.get("verdict") or "") + " " + (row.get("note") or "")
            assert re.search(r"illegal|probe|must fail", txt, re.I), (
                f"{row['path']} fails the format contract but the site does not say so: {txt!r}")
        else:
            assert any(row["path"] in n for n in man.get("notes", [])), (
                f"{row['path']} is format-illegal in a lane directory and the audit says nothing "
                "about it; it must at least be named in the notes")


def test_evidence_cited_by_a_verdict_exists():
    for row in _manifest()["files"]:
        for ev in row.get("evidence") or []:
            assert (ROOT / ev).exists(), f"{row['path']}: verdict cites {ev}, which does not exist"


def test_every_link_on_the_public_pages_is_audited():
    man = _manifest()
    by_name = {pathlib.Path(r["path"]).name: r for r in man["files"]}
    for page in PAGES:
        f = ROOT / page
        if not f.exists():
            continue
        for m in re.finditer(r'href="([^"]*downloads/[^"]+\.tif)"', f.read_text(errors="ignore")):
            name = m.group(1).split("/")[-1]
            assert name in by_name, f"{page} links {name}, which the audit has never seen"
            assert by_name[name].get("verdict"), f"{page} links {name} with no verdict on record"


def test_stale_verdict_on_a_regenerated_file_is_caught(tmp_path):
    """Re-emit a legal raster, hand it the wrong pinned sha, and show the audit refuses it."""
    audit = _audit()
    import numpy as np
    arr = np.zeros(G.SHAPE, np.float32)
    arr[1000, 1000] = 1.0
    arr[1200, 1400] = 1.0
    arr[1500, 1800] = 1.0
    out = tmp_path / "gems62-test-regenerated.tif"
    G.write_submission(out, arr)
    side = tmp_path / "gems62-test-regenerated.verdict.json"
    side.write_text(json.dumps({"verdict": "TEST", "ok_to_submit": False,
                                "sha256": "0" * 64, "bytes": 12345}))
    foot = np.ones(G.SHAPE, bool)
    cat = np.zeros(G.SHAPE, bool)
    row = audit.audit_file(out, tmp_path, foot, cat)
    assert row["dots"] == 3
    assert row["sidecar_matches_bytes"] is False
    assert "different bytes" in row["sidecar_error"]
    again = audit.audit_file(out, tmp_path, foot, cat,
                             claim={"verdict": "TEST", "ok_to_submit": False}, write_sidecar=True)
    assert again["sidecar_matches_bytes"] is True, "the generated sidecar must match its own bytes"
    assert json.loads(side.read_text())["sha256"] == row["sha256"]


def test_pages_may_not_print_a_hash_that_disagrees_with_the_file(tmp_path):
    audit = _audit()
    name, sha, size = "x.tif", "ab" * 32, 91954
    page = tmp_path / "docs" / "index.html"
    page.parent.mkdir(parents=True)
    page.write_text(f'<table><tr><td><a href="downloads/{name}">{name}</a></td>'
                     f'<td>{"cd" * 32}</td><td>{size:,} B</td></tr></table>')
    bad = audit.cross_check_page(tmp_path, name, {"sha256": sha, "bytes": size}, ["docs/index.html"])
    assert len(bad) == 1 and "prints hash" in bad[0], bad
    page.write_text(f'<table><tr><td><a href="downloads/{name}">{name}</a></td>'
                    f'<td>{sha[:12]}</td><td>{size + 1:,} B</td></tr></table>')
    bad = audit.cross_check_page(tmp_path, name, {"sha256": sha, "bytes": size}, ["docs/index.html"])
    assert len(bad) == 1 and "the file on disk is" in bad[0], bad
    page.write_text(f'<table><tr><td><a href="downloads/{name}">{name}</a></td>'
                    f'<td>{sha[:12]}</td><td>{size:,} B</td></tr></table>')
    assert audit.cross_check_page(tmp_path, name, {"sha256": sha, "bytes": size},
                                  ["docs/index.html"]) == []


def test_verdicts_json_only_names_downloadable_rasters():
    claims = json.loads((DL / "verdicts.json").read_text())
    have = {p.name for p in ROOT.glob("docs/downloads/*.tif")} | {p.name for p in ROOT.glob("*/docs/downloads/*.tif")}
    assert set(claims) <= have, f"claims for files that are not there: {set(claims) - have}"
    for name, v in claims.items():
        assert v.get("verdict") and v.get("note"), f"{name}: verdict and note are both required"
        assert "ok_to_submit" in v, f"{name}: must state whether it is OK to submit"
        assert isinstance(v["ok_to_submit"], bool)
